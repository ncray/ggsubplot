# Run from the repository root with Rscript tools/generate-synthetic-data.R.
# Historical object/column names are retained for example compatibility only.

nasa <- expand.grid(x = seq_len(12), y = seq_len(10),
  time = seq_len(72), KEEP.OUT.ATTRS = FALSE)
nasa$long <- -112 + 2 * (nasa$x - 1)
nasa$lat <- 25 + 2 * (nasa$y - 1)
nasa$month <- (nasa$time - 1) %% 12 + 1
nasa$year <- 1995 + (nasa$time - 1) %/% 12
nasa$day <- 1
nasa$date <- as.POSIXct(sprintf("%04d-%02d-01", nasa$year, nasa$month), tz = "UTC")
season <- sin(2 * pi * (nasa$month - 4) / 12)
nasa$surftemp <- 290 - 0.6 * (nasa$lat - 25) + 9 * season +
  2 * cos(nasa$x / 3) + 0.15 * (nasa$year - 1995)
nasa$temperature <- nasa$surftemp - 4
nasa$cloudhigh <- 20 + 10 * sin(nasa$x / 3 + nasa$month / 2)
nasa$cloudlow <- 35 + 15 * cos(nasa$y / 3 + nasa$month / 2)
nasa$cloudmid <- 25 + 10 * sin(nasa$y / 4 - nasa$month / 2)
nasa$ozone <- as.integer(260 + 20 * season + nasa$y)
nasa$pressure <- as.integer(1010 - 2 * nasa$y + 3 * cos(nasa$x))
nasa$id <- sprintf("synthetic-%02d-%02d", nasa$x, nasa$y)
nasa <- nasa[c("time", "y", "x", "lat", "long", "date", "cloudhigh",
  "cloudlow", "cloudmid", "ozone", "pressure", "surftemp", "temperature",
  "id", "day", "month", "year")]
attr(nasa, "provenance") <- "Entirely synthetic; not NASA observations. Generated by tools/generate-synthetic-data.R."

# Fictional events, not records of people or an actual conflict.
i <- seq_len(2400)
date <- as.POSIXct("2004-01-01", tz = "UTC") + ((i * 37L) %% 1096L) * 86400
victim <- factor(c("enemy", "civilian", "host", "friendly")[(i * 7L + i %/% 11L) %% 4L + 1L],
  levels = c("enemy", "civilian", "host", "friendly"))
fatal <- i %% 3L == 0L
casualties <- data.frame(date = date,
  year = as.numeric(format(date, "%Y", tz = "UTC")),
  month = ordered(as.integer(format(date, "%m", tz = "UTC")),
    levels = 1:12, labels = month.name),
  day = ordered(as.integer(format(date, "%w", tz = "UTC")), levels = 0:6,
    labels = c("Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday")),
  lon = 61 + 13 * ((i * 137L) %% 2399L) / 2399,
  lat = 30 + 8 * ((i * 311L) %% 2399L) / 2399,
  fatal = fatal, harmful = TRUE, type = "Synthetic event",
  category = "Fictional example", victim = victim,
  casualty = ifelse(fatal, "Synthetic fatal", "Synthetic injury"))
attr(casualties, "provenance") <- "Entirely synthetic fictional events; not Afghan War Diary records. Generated by tools/generate-synthetic-data.R."

save(nasa, file = "data/nasa.rda", version = 2, compress = "xz")
save(casualties, file = "data/casualties.rda", version = 2, compress = "xz")
